// Emits a device tree (sacris_v.dts) describing the elaborated configuration.

package sacris_v

object DtsGenerator {

  private val A = AddressMap

  def generate(p: TopParams): String = {
    val timebaseFreq = p.clkHz / p.timerTickCompare

    val isa = {
      val base = "rv32i"
      val m = if (p.enableMExtension) "m" else ""
      val f = if (p.enableFExtension) "f" else ""
      val c = if (p.enableCExtension) "c" else ""
      val zicsr = "_zicsr_zifencei"
      val bexts = if (p.enableBExtension) "_zba_zbb_zbc_zbs" else ""
      s"$base$m$f$c$zicsr$bexts"
    }

    val model = {
      val m = if (p.enableMExtension) "M" else ""
      val f = if (p.enableFExtension) "F" else ""
      val c = if (p.enableCExtension) "C" else ""
      val b = if (p.enableBExtension) "B" else ""
      s"SaCriS-V RV32I${m}${f}${c}${b}"
    }

    val dmemBytes = p.dmemSize.toLong * 4
    val imemBytes = p.imemSize.toLong * 4

    def hex(v: Long): String = f"0x${v}%08x"

    val sb = new StringBuilder
    sb.append("/* Auto-generated by DtsGenerator.scala — do not edit manually */\n")
    sb.append("/dts-v1/;\n\n")
    sb.append("/ {\n")
    sb.append("    #address-cells = <1>;\n")
    sb.append("    #size-cells = <1>;\n")
    sb.append("    compatible = \"sacris-v,sacris-v\";\n")
    sb.append(s"""    model = "$model";\n""")
    sb.append("\n")

    sb.append("    chosen {\n")
    sb.append("        bootargs = \"\";\n")
    sb.append("        stdout-path = &uart0;\n")
    sb.append("        zephyr,console = &uart0;\n")
    sb.append("        zephyr,shell-uart = &uart0;\n")
    sb.append("        zephyr,sram = &dmem;\n")
    sb.append("        zephyr,flash = &imem;\n")
    sb.append("    };\n\n")

    sb.append("    cpus {\n")
    sb.append("        #address-cells = <1>;\n")
    sb.append("        #size-cells = <0>;\n")
    sb.append(s"        timebase-frequency = <$timebaseFreq>;\n\n")
    sb.append("        cpu0: cpu@0 {\n")
    sb.append("            compatible = \"riscv\";\n")
    sb.append("            device_type = \"cpu\";\n")
    sb.append("            reg = <0>;\n")
    sb.append(s"""            riscv,isa = "$isa";\n""")
    sb.append("            mmu-type = \"riscv,none\";\n")
    sb.append(s"            clock-frequency = <${p.clkHz}>;\n")

    if (p.enableMExtension) sb.append("            sacris-v-ext-m;\n")
    if (p.enableFExtension) sb.append("            sacris-v-ext-f;\n")
    if (p.enableCExtension) sb.append("            sacris-v-ext-c;\n")
    if (p.enableBExtension) sb.append("            sacris-v-ext-b;\n")
    sb.append("            status = \"okay\";\n\n")
    sb.append("            cpu0_intc: interrupt-controller {\n")
    sb.append("                compatible = \"riscv,cpu-intc\";\n")
    sb.append("                #interrupt-cells = <1>;\n")
    sb.append("                interrupt-controller;\n")
    sb.append("            };\n")
    sb.append("        };\n")
    sb.append("    };\n\n")

    sb.append(s"    dmem: memory@${f"${A.DMEM_BASE}%x"} {\n")
    sb.append("        device_type = \"memory\";\n")
    sb.append("        compatible = \"mmio-sram\";\n")
    sb.append(s"        reg = <${hex(A.DMEM_BASE)} ${hex(dmemBytes)}>;\n")
    sb.append("    };\n\n")

    sb.append(s"    imem: memory@${f"${A.IMEM_BASE}%x"} {\n")
    sb.append("        compatible = \"soc-nv-flash\";\n")
    sb.append(s"        reg = <${hex(A.IMEM_BASE)} ${hex(imemBytes)}>;\n")
    sb.append("    };\n\n")

    if (p.withDmaMem) {
      val dmaMemBytes = p.dmaMemSize.toLong * 4
      sb.append(s"    dmamem: memory@${f"${A.DMA_MEM_BASE}%x"} {\n")
      sb.append("        compatible = \"sacris-v,dma-mem\";\n")
      sb.append(s"        reg = <${hex(A.DMA_MEM_BASE)} ${hex(dmaMemBytes)}>;\n")
      sb.append("        status = \"okay\";\n")
      sb.append("    };\n\n")
    }

    sb.append("    soc {\n")
    sb.append("        #address-cells = <1>;\n")
    sb.append("        #size-cells = <1>;\n")
    sb.append("        compatible = \"simple-bus\";\n")
    sb.append("        ranges;\n\n")

    sb.append(s"        mswi: interrupt-controller@${f"${A.ACLINT_MSWI_BASE}%x"} {\n")
    sb.append("            compatible = \"riscv,aclint-mswi\";\n")
    sb.append(s"            reg = <${hex(A.ACLINT_MSWI_BASE)} ${hex(A.ACLINT_MSWI_SIZE)}>;\n")
    sb.append("            interrupts-extended = <&cpu0_intc 3>;\n")
    sb.append("        };\n\n")

    sb.append(s"        mtimer: timer@${f"${A.ACLINT_MTIMECMP_BASE}%x"} {\n")
    sb.append("            compatible = \"riscv,machine-timer\";\n")
    sb.append(s"            reg = <${hex(A.ACLINT_MTIMECMP_BASE)} ${hex(A.ACLINT_MTIMECMP_SIZE)} ${hex(A.ACLINT_MTIME_BASE)} ${hex(A.ACLINT_MTIME_SIZE)}>;\n")
    sb.append("            reg-names = \"mtimecmp\", \"mtime\";\n")
    sb.append("            interrupts-extended = <&cpu0_intc 7>;\n")
    sb.append("        };\n\n")

    sb.append(s"        plic: interrupt-controller@${f"${A.PLIC_BASE}%x"} {\n")
    sb.append("            compatible = \"sifive,plic-1.0.0\";\n")
    sb.append(s"            reg = <${hex(A.PLIC_BASE)} ${hex(A.PLIC_SIZE)}>;\n")
    sb.append("            #address-cells = <0>;\n")
    sb.append("            #interrupt-cells = <2>;\n")
    sb.append("            interrupt-controller;\n")
    sb.append("            interrupts-extended = <&cpu0_intc 11>;\n")
    sb.append(s"            riscv,max-priority = <${A.PLIC_MAX_PRIORITY}>;\n")
    sb.append(s"            riscv,ndev = <${A.PLIC_NUM_SOURCES}>;\n")
    sb.append("        };\n\n")

    sb.append(s"        sim_end: poweroff@${f"${A.SIMULATION_END_ADDR}%x"} {\n")
    sb.append("            compatible = \"sacris-v,sim-end\";\n")
    sb.append(s"            reg = <${hex(A.SIMULATION_END_ADDR)} 0x00000004>;\n")
    sb.append("            status = \"okay\";\n")
    sb.append("        };\n\n")

    sb.append(s"        uart0: serial@${f"${A.UART16550_BASE}%x"} {\n")
    sb.append("            compatible = \"ns16550\";\n")
    sb.append(s"            reg = <${hex(A.UART16550_BASE)} ${hex(A.UART16550_SIZE)}>;\n")
    sb.append(s"            reg-shift = <${A.UART16550_REG_SHIFT}>;\n")
    sb.append(s"            clock-frequency = <${p.clkHz}>;\n")
    sb.append(s"            current-speed = <${p.uartBaud}>;\n")
    sb.append("            interrupt-parent = <&plic>;\n")
    sb.append(s"            interrupts = <${A.PLIC_SRC_UART16550} 1>;\n")
    sb.append("            status = \"okay\";\n")
    sb.append("        };\n\n")

    if (p.withWDT) {
      sb.append(s"        wdt: watchdog@${f"${A.WDT_BASE}%x"} {\n")
      sb.append("            compatible = \"sacris-v,wdt\";\n")
      sb.append(s"            reg = <${hex(A.WDT_BASE)} ${hex(A.WDT_SIZE)}>;\n")
      sb.append("            status = \"okay\";\n")
      sb.append("        };\n\n")
    }

    if (p.withSPI) {
      sb.append(s"        spi: spi@${f"${A.SPI_BASE}%x"} {\n")
      sb.append("            compatible = \"sacris-v,spi\";\n")
      sb.append(s"            reg = <${hex(A.SPI_BASE)} ${hex(A.SPI_SIZE)}>;\n")
      sb.append("            status = \"okay\";\n")
      sb.append("        };\n\n")
    }

    if (p.withDmaController) {
      val dmaCtrlTotalSize = p.dmaChannels.toLong * A.DMA_CTRL_CHANNEL_SPACING
      val irqList = (0 until p.dmaChannels).map(i => s"<${9 + i} 1>").mkString(", ")
      sb.append(s"        dma: dma-controller@${f"${A.DMA_CTRL_BASE}%x"} {\n")
      sb.append("            compatible = \"sacris-v,dma\";\n")
      sb.append(s"            reg = <${hex(A.DMA_CTRL_BASE)} ${hex(dmaCtrlTotalSize)}>;\n")
      sb.append("            interrupt-parent = <&plic>;\n")
      sb.append(s"            interrupts = $irqList;\n")
      sb.append("            #dma-cells = <1>;\n")
      sb.append(s"            dma-channels = <${p.dmaChannels}>;\n")
      sb.append("            status = \"okay\";\n")
      sb.append("        };\n\n")
    }

    if (p.withDmaTestSource) {
      for (i <- 0 until p.dmaTestSourceCount) {
        val srcBase = A.DMA_TEST_SOURCE_BASE + i.toLong * A.DMA_TEST_SOURCE_SPACING
        val label = if (i == 0) "dma_test_source" else s"dma_test_source_$i"
        sb.append(s"        $label: dma-test-source@${f"$srcBase%x"} {\n")
        sb.append("            compatible = \"sacris-v,dma-test-source\";\n")
        sb.append(s"            reg = <${hex(srcBase)} ${hex(A.DMA_TEST_SOURCE_SIZE)}>;\n")
        sb.append("            status = \"okay\";\n")
        sb.append("        };\n\n")
      }
    }

    if (p.withI2C) {
      sb.append(s"        i2c: i2c@${f"${A.I2C_BASE}%x"} {\n")
      sb.append("            compatible = \"sacris-v,i2c\";\n")
      sb.append(s"            reg = <${hex(A.I2C_BASE)} ${hex(A.I2C_SIZE)}>;\n")
      sb.append("            status = \"okay\";\n")
      sb.append("        };\n\n")
    }

    sb.append("    };\n")
    sb.append("};\n")

    sb.toString()
  }
}
